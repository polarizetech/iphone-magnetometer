# ----------------------------------------------------------------------------- helpers

def _iso_to_epoch(text: str) -> float:
    text = text.strip().replace("Z", "+00:00")
    value = datetime.fromisoformat(text)
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    return value.timestamp()


def _epoch_to_iso(value: float) -> str:
    return datetime.fromtimestamp(value, tz=timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def _atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".partial")
    with open(temp, "wb") as handle:
        handle.write(data)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temp, path)


def _valid_id(value) -> bool:
    return isinstance(value, str) and bool(ID_RE.match(value))


# ----------------------------------------------------------------------------- the store

class Store:
    """Everything under `streams/`. One lock; disk is the truth, memory is an index of it."""

    def __init__(self, root: Path):
        self.root = root
        self.lock = threading.RLock()
        self.listeners: list[queue.Queue] = []
        root.mkdir(parents=True, exist_ok=True)

    # -- paths
    def stream_dir(self, device: str, stream: str) -> Path:
        return self.root / device / stream

    def manifest_path(self, device: str, stream: str) -> Path:
        return self.stream_dir(device, stream) / "manifest.jsonl"

    # -- reading
    def manifest(self, device: str, stream: str) -> list[dict]:
        path = self.manifest_path(device, stream)
        if not path.exists():
            return []
        rows = []
        for line in path.read_text().splitlines():
            line = line.strip()
            if line:
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError:
                    continue  # a torn last line from a crash mid-append; the chunk file is still there
        # One row per seq; a retry after a lost row can log it again (ingest), so keep the last.
        by_seq: dict[int, dict] = {}
        for row in rows:
            by_seq[row["seq"]] = row
        return [by_seq[k] for k in sorted(by_seq)]

    @staticmethod
    def missing(rows: list[dict]) -> list[int]:
        if not rows:
            return []
        have = {r["seq"] for r in rows}
        top = max(have)
        return [s for s in range(top + 1) if s not in have]

    def devices(self) -> list[str]:
        return sorted(p.name for p in self.root.iterdir() if p.is_dir() and _valid_id(p.name))

    def streams(self, device: str) -> list[str]:
        d = self.root / device
        if not d.is_dir():
            return []
        return sorted(p.name for p in d.iterdir() if p.is_dir() and _valid_id(p.name))

    def stream_summary(self, device: str, stream: str) -> dict:
        rows = self.manifest(device, stream)
        info = {}
        meta = self.stream_dir(device, stream) / "stream.json"
        if meta.exists():
            try:
                info = json.loads(meta.read_text())
            except json.JSONDecodeError:
                info = {}
        if rows:
            first, last = rows[0], rows[-1]
            summary = {
                "device": device, "stream": stream,
                "chunks": len(rows), "missing": self.missing(rows),
                "samples": sum(r.get("sampleCount", 0) for r in rows),
                "from": first["startedAt"], "to": last["endedAt"],
                "fromEpoch": _iso_to_epoch(first["startedAt"]), "toEpoch": _iso_to_epoch(last["endedAt"]),
                "rateHz": last.get("achievedRateHz"),
                "emitter": any(r.get("emitter") for r in rows),
                # The phone's covariates from the most recent chunk: battery, thermal, barometric
                # pressure, free disk. Absent from older chunks, which is not an error.
                "aux": last.get("aux"),
                "lastReceivedAt": last.get("receivedAt"),
            }
        else:
            summary = {"device": device, "stream": stream, "chunks": 0, "missing": [], "samples": 0}
        summary["info"] = info
        return summary

    def status(self) -> dict:
        out = []
        for device in self.devices():
            streams = [self.stream_summary(device, s) for s in self.streams(device)]
            streams.sort(key=lambda s: s.get("fromEpoch", 0))
            latest = streams[-1] if streams else None
            out.append({
                "device": device,
                "name": (latest or {}).get("info", {}).get("deviceName") if latest else None,
                "streams": streams,
                "latest": latest,
            })
        return {"devices": out, "now": time.time(), "analysisVenv": ANALYSIS_PY.exists()}

    # -- writing
    def ingest(self, body: bytes, compression: str) -> dict:
        if compression in ("deflate-raw", "deflate"):
            decomp = zlib.decompressobj(-15)
            try:
                file = decomp.decompress(body, MAX_CHUNK_BYTES + 1)
            except zlib.error as exc:
                raise ValueError(f"deflate: {exc}") from exc
            if len(file) > MAX_CHUNK_BYTES or decomp.unconsumed_tail:
                raise ValueError("chunk too large")
        elif compression in ("none", "identity", ""):
            file = body
        else:
            raise ValueError(f"unknown compression {compression!r}")
        newline = file.find(b"\n")
        if newline < 0:
            raise ValueError("no header line")
        try:
            header = json.loads(file[:newline])
        except json.JSONDecodeError as exc:
            raise ValueError(f"header is not JSON: {exc}") from exc
        if header.get("format") != FORMAT:
            raise ValueError(f"format {header.get('format')!r} is not {FORMAT}")
        device, stream, seq = header.get("deviceID"), header.get("streamID"), header.get("seq")
        if not (_valid_id(device) and _valid_id(stream) and isinstance(seq, int) and seq >= 0):
            raise ValueError("bad deviceID / streamID / seq")
        # Every reader of the manifest does arithmetic on these; one bad row used to break /api/status.
        if not (isinstance(header.get("sampleCount"), int) and header["sampleCount"] >= 0):
            raise ValueError("sampleCount must be a non-negative integer")
        for key in ("startedAt", "endedAt"):
            try:
                _iso_to_epoch(header[key])
            except (KeyError, AttributeError, TypeError, ValueError):
                raise ValueError(f"{key} must be an ISO-8601 time") from None
        csv_bytes = file[newline + 1:]
        digest = hashlib.sha256(csv_bytes).hexdigest()
        if header.get("sha256") != digest:
            raise ValueError("sha256 mismatch: the bytes received are not the bytes the phone described")
        first_line = csv_bytes.split(b"\n", 1)[0].decode("utf-8", "replace")
        if first_line.strip() != CSV_HEADER:
            raise ValueError("CSV header is not the raw.csv column set")

        with self.lock:
            chunk_path = self.stream_dir(device, stream) / "chunks" / f"{seq:06d}.csv"
            duplicate = False
            if chunk_path.exists():
                existing = hashlib.sha256(chunk_path.read_bytes()).hexdigest()
                if existing != digest:
                    raise ChunkConflict(f"seq {seq} is already stored with different bytes; the stored chunk is kept")
                duplicate = True
            # A crash between writing the file and appending its row left the chunk on disk but out of
            # the manifest, and the phone's retry then read as a duplicate. The retry writes the row.
            logged = duplicate and any(r.get("seq") == seq for r in self.manifest(device, stream))
            if not duplicate:
                _atomic_write(chunk_path, csv_bytes)
            if not logged:
                row = {k: header.get(k) for k in ("seq", "startedAt", "endedAt", "firstMonotonic", "lastMonotonic",
                                                  "sampleCount", "requestedRateHz", "achievedRateHz", "emitter",
                                                  "aux", "sha256", "deviceName", "deviceModel", "systemVersion",
                                                  "appVersion")}
                row["receivedAt"] = _epoch_to_iso(time.time())
                row["bytes"] = len(csv_bytes)
                with open(self.manifest_path(device, stream), "a") as handle:
                    handle.write(json.dumps(row, separators=(",", ":")) + "\n")
                    handle.flush()
                    os.fsync(handle.fileno())
                self._touch_stream_json(device, stream, header)
            rows = self.manifest(device, stream)
            missing = self.missing(rows)

        event = {
            "device": device, "stream": stream, "seq": seq, "duplicate": duplicate,
            "startedAt": header.get("startedAt"), "endedAt": header.get("endedAt"),
            "sampleCount": header.get("sampleCount"), "achievedRateHz": header.get("achievedRateHz"),
            "emitter": header.get("emitter"), "missing": missing[-50:], "chunks": len(rows),
        }
        if not duplicate:
            self.publish("chunk", event)
        return {"ok": True, "seq": seq, "duplicate": duplicate, "stored": str(chunk_path.relative_to(self.root)),
                "missing": missing[-50:], "message": f"chunk {seq} {'already held' if duplicate else 'stored'}; "
                f"{len(rows)} in stream, {len(missing)} missing"}

    def _touch_stream_json(self, device: str, stream: str, header: dict) -> None:
        path = self.stream_dir(device, stream) / "stream.json"
        info = {}
        if path.exists():
            try:
                info = json.loads(path.read_text())
            except json.JSONDecodeError:
                info = {}
        for key in ("deviceName", "deviceModel", "systemVersion", "appVersion", "requestedRateHz"):
            if header.get(key) is not None:
                info[key] = header[key]
        info.setdefault("firstSeenAt", _epoch_to_iso(time.time()))
        info["lastChunkAt"] = _epoch_to_iso(time.time())
        info["deviceID"], info["streamID"] = device, stream
        _atomic_write(path, json.dumps(info, indent=2, sort_keys=True).encode())

    def hello(self, payload: dict) -> dict:
        device, stream = payload.get("deviceID"), payload.get("streamID")
        if not (_valid_id(device) and _valid_id(stream)):
            raise ValueError("bad deviceID / streamID")
        with self.lock:
            path = self.stream_dir(device, stream) / "stream.json"
            info = {}
            if path.exists():
                try:
                    info = json.loads(path.read_text())
                except json.JSONDecodeError:
                    info = {}
            info.update({k: v for k, v in payload.items() if k not in ("deviceID", "streamID")})
            info["deviceID"], info["streamID"] = device, stream
            info.setdefault("firstSeenAt", _epoch_to_iso(time.time()))
            info["helloAt"] = _epoch_to_iso(time.time())
            _atomic_write(path, json.dumps(info, indent=2, sort_keys=True).encode())
        self.publish("hello", {"device": device, "stream": stream, "deviceName": payload.get("deviceName")})
        return {"ok": True, "message": f"hello {device}/{stream}"}

    # -- samples
    def samples(self, device: str, t0: float, t1: float, step: int = 1, stream: str | None = None) -> dict:
        """Rows whose wall time falls in [t0, t1], as columns. `step > 1` bin-averages."""
        cols = {"t": [], "mx": [], "my": [], "mz": [], "mag": []}
        chunks_used = 0
        emitter = False
        streams = [stream] if stream else self.streams(device)
        for s in streams:
            for row in self.manifest(device, s):
                a, b = _iso_to_epoch(row["startedAt"]), _iso_to_epoch(row["endedAt"])
                if b < t0 or a > t1:
                    continue
                path = self.stream_dir(device, s) / "chunks" / f"{row['seq']:06d}.csv"
                if not path.exists():
                    continue
                chunks_used += 1
                emitter = emitter or bool(row.get("emitter"))
                anchor = a - float(row.get("firstMonotonic") or 0.0)
                with open(path) as handle:
                    next(handle, None)
                    for line in handle:
                        parts = line.split(",", 6)
                        if len(parts) < 6:
                            continue
                        try:
                            t = anchor + float(parts[0])
                            mx, my, mz, mag = (float(v) for v in parts[2:6])
                        except ValueError:          # an empty or garbled field drops the row
                            continue
                        if t < t0 or t > t1:
                            continue
                        cols["t"].append(t)
                        cols["mx"].append(mx)
                        cols["my"].append(my)
                        cols["mz"].append(mz)
                        cols["mag"].append(mag)
        # sort by time across streams (streams do not overlap, but be safe)
        if cols["t"] and any(cols["t"][i] > cols["t"][i + 1] for i in range(len(cols["t"]) - 1)):
            order = sorted(range(len(cols["t"])), key=cols["t"].__getitem__)
            for k in cols:
                cols[k] = [cols[k][i] for i in order]
        gaps = []
        rate = None
        t = cols["t"]
        if len(t) > 2:
            dts = sorted(t[i + 1] - t[i] for i in range(len(t) - 1) if t[i + 1] > t[i])
            if dts:
                median = dts[len(dts) // 2]
                rate = 1 / median if median > 0 else None
                for i in range(len(t) - 1):
                    if t[i + 1] - t[i] > 3 * median:
                        gaps.append([t[i], t[i + 1]])
        if step > 1 and t:
            binned = {k: [] for k in cols}
            for i in range(0, len(t), step):
                j = min(i + step, len(t))
                n = j - i
                for k in cols:
                    binned[k].append(sum(cols[k][i:j]) / n)
            cols = binned
        return {"device": device, "from": t0, "to": t1, "n": len(cols["t"]), "step": step, "rateHz": rate,
                "gaps": gaps, "chunks": chunks_used, "emitter": emitter, **cols}

    # -- events
    def subscribe(self) -> queue.Queue:
        q: queue.Queue = queue.Queue(maxsize=256)
        with self.lock:
            self.listeners.append(q)
        return q

    def unsubscribe(self, q: queue.Queue) -> None:
        with self.lock:
            if q in self.listeners:
                self.listeners.remove(q)

    def publish(self, event: str, data: dict) -> None:
        with self.lock:
            listeners = list(self.listeners)
        for q in listeners:
            try:
                q.put_nowait((event, data))
            except queue.Full:
                pass


