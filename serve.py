#: The most recent `alerts` result per device, so the page can show a banner without re-running a
#: two-minute job on every load. It carries the window it was computed over and when — an alert
#: with no window is a claim about nothing in particular.
LATEST_ALERTS: dict[str, dict] = {}

#: The most recent professional-station reference profile, keyed by device. Cached the same way as
#: the alerts, and carrying its source so the page can say where a number came from.
LATEST_STATION: dict[str, dict] = {}


class Jobs:
    """`analysis/run.py` as subprocesses. The server stays stdlib; numpy lives in the venv."""

    def __init__(self):
        self.lock = threading.Lock()
        self.jobs: dict[str, dict] = {}
        self.counter = 0

    def start(self, command: str, device: str, t0: float, t1: float, extra: list[str]) -> dict:
        if command not in ANALYZE_COMMANDS:
            raise ValueError(f"command must be one of {ANALYZE_COMMANDS}")
        if not _valid_id(device):
            raise ValueError("bad device")
        if not ANALYSIS_PY.exists():
            raise ValueError("analysis venv missing — see analysis/README.md")
        if not all(math.isfinite(t) and 0 <= t < 4e9 for t in (t0, t1)) or t0 > t1:
            raise ValueError("from/to must be epoch seconds, with from <= to")
        # Every value is a flag's argument: nothing may reach run.py as a positional of its own.
        for i, x in enumerate(extra):
            if not x.startswith("-") and (i == 0 or not extra[i - 1].startswith("-")):
                raise ValueError(f"{x!r} is not the value of a flag")
        if command == "station":
            # A station profile is not a window of THIS device's stream — it reads a remote archive.
            argv = [str(ANALYSIS_PY), str(ANALYSIS / "run.py"), "station", *extra]
        else:
            argv = [str(ANALYSIS_PY), str(ANALYSIS / "run.py"), command, "--stream", str(STREAMS / device),
                    "--from", _epoch_to_iso(t0), "--to", _epoch_to_iso(t1), *extra]
        with self.lock:
            if sum(j["state"] == "running" for j in self.jobs.values()) >= MAX_RUNNING_JOBS:
                raise ValueError(f"{MAX_RUNNING_JOBS} jobs are already running; wait for one to finish")
            self.counter += 1
            job_id = f"job-{self.counter:04d}"
            job = {"id": job_id, "command": command, "device": device, "from": t0, "to": t1,
                   "state": "running", "startedAt": time.time(), "output": "", "returncode": None}
            self.jobs[job_id] = job
        threading.Thread(target=self._run, args=(job_id, argv), daemon=True).start()
        # What ran, without this machine's paths.
        shown = ["run.py", *(f"streams/{device}" if a == str(STREAMS / device) else a for a in argv[2:])]
        return {"ok": True, "job": job_id, "argv": shown}

    def _run(self, job_id: str, argv: list[str]) -> None:
        try:
            proc = subprocess.run(argv, capture_output=True, text=True, timeout=1800, cwd=str(HERE))
            output, code = (proc.stdout or "") + (("\n[stderr]\n" + proc.stderr) if proc.stderr else ""), proc.returncode
        except subprocess.TimeoutExpired:
            output, code = "timed out after 1800 s", -1
        except Exception as exc:  # noqa: BLE001
            output, code = f"failed to start: {exc}", -1
        with self.lock:
            job = self.jobs[job_id]
            job.update(state="done" if code == 0 else "failed", output=output[-200_000:], returncode=code,
                       endedAt=time.time())
            command, device = job["command"], job["device"]
            window = (job["from"], job["to"])
        if code == 0 and command == "station":
            try:
                LATEST_STATION[device] = dict(json.loads(output), computedAt=time.time(), job=job_id)
                STORE.publish("station", {"device": device})
            except (json.JSONDecodeError, TypeError, ValueError):
                pass
        if code == 0 and command == "alerts":
            # Cache the parsed banner payload. A parse failure is not fatal — the job's raw output is
            # still there to read, and a banner that cannot be built is simply not shown.
            try:
                parsed = json.loads(output)
                LATEST_ALERTS[device] = {
                    "device": device, "from": window[0], "to": window[1],
                    "computedAt": time.time(), "job": job_id,
                    "alerts": parsed.get("alerts", {}),
                    "minimumDetectableNt": parsed.get("minimum_detectable_nt"),
                }
                STORE.publish("alerts", {"device": device,
                                         "count": parsed.get("alerts", {}).get("count", 0)})
            except (json.JSONDecodeError, AttributeError):
                pass
        STORE.publish("job", {"id": job_id, "state": self.jobs[job_id]["state"]})

    def list(self) -> list[dict]:
        with self.lock:
            return [dict(j, output=(j["output"][-4000:] if j["state"] == "running" else j["output"]))
                    for j in sorted(self.jobs.values(), key=lambda j: j["startedAt"], reverse=True)]


STORE = Store(STREAMS)
JOBS = Jobs()


