#!/usr/bin/env python3
"""FieldLab's Mac half: receive the phone's always-on stream, keep it, and show it.

    python3 serve.py            # http://127.0.0.1:8212/
    python3 serve.py 8300       # any port

The phone posts to `<server URL>/api/stream/chunk`; set the server URL in the app's Stream settings.
Behind a reverse proxy that mounts it under a path prefix (GATEWAY_PREFIXES), every route here is
still rooted at `/`, and the web page fetches by RELATIVE path so it works both ways.

What it owns
------------
* `POST /api/stream/chunk`  — one spool file from the phone: a raw-DEFLATE body whose first line
  is a JSON header and the rest is `raw.csv` (same columns as an export). Stored DECOMPRESSED
  under `streams/<device>/<stream>/chunks/<seq>.csv`, one manifest line appended per chunk, and
  acknowledged with the sequence numbers this server has NOT seen — so a gap is reported the
  moment it exists. Idempotent: a retried upload of the same bytes is a `duplicate`, not a second
  chunk. The gateway may retry a POST once, so that is load-bearing.
* `POST /api/stream/hello`  — the phone's settings and identity at Start. Optional; a chunk
  header carries enough to reconstruct a stream without it.
* Each chunk header may carry an `aux` block (battery, thermal state, barometric pressure, free
  disk) and a structured `emitter` stamp (carrier, code, chip) when the phone was running its own
  positive control. Both are optional — an older chunk without them is not an error.
* `GET  /api/events`        — SSE: a `chunk` event per arrival plus a heartbeat, so the page can
  redraw when something lands rather than polling.
* `GET  /api/samples`       — a time window of samples for one device, optionally bin-averaged,
  with the dropped-sample gaps the window contains. Served from disk, never from a second copy.
* `GET  /api/findings`      — the consuming analysis's summary, generated by its `run.py summary`
  and served as a static file. **It reads cached artefacts and never fetches.**
* `GET  /api/station`       — the latest reference-station profile, cached from the last `station`
  job of the consuming analysis.
* `GET  /api/register`      — the signal register: every signal ever logged for a device, with its
  fingerprint, its automatic test results, and which manual tests are still outstanding.
* `POST /api/register/confirm` — record that a person actually ran a manual test, and what happened.
* `GET  /api/watch`        — the consuming analysis's live reading of the line it is watching (its
  `run.py watch`), shelled out to that analysis's venv and briefly cached, because the page polls it.
* `GET  /api/runbook`      — the manual tests as coached steps, what has been ticked, and what is
  safe to do right now given `/api/watch`. Imported directly: `runbook.py` is stdlib on purpose.
* `POST /api/runbook/step` — tick or untick one step, recording the GATE STATE at that moment.
* `POST /api/runbook/reset`— archive an attempt and start that test again. Appends, never deletes.
* `GET  /watch`            — the consuming analysis's own page, if it ships one (`CLAIM_WEB`).
* `GET  /api/alerts`        — the most recent "what in this record is not noise" scan for a device,
  cached from the last `alerts` job. Carries the window it was computed over and when.
* `GET  /api/bands`         — the band registry, PARSED OUT OF `BandRegistry.swift` at request
  time. One source of truth for "what is a known band"; the web page reads this, not a copy.
* `POST /api/analyze`       — run `analysis/run.py <command>` over a window of stream, in the
  sidecar's own venv, as a job. The server itself is stdlib-only; numpy lives in `analysis/`.

What it refuses
---------------
* any URL segment named `research`, `subjects` or `recordings` (proxies that guard private data
  often refuse those names, and a route that works only on localhost is a trap);
* static reads under `streams/` (the data folder is not on the URL surface) and any `.py`;
* a chunk whose SHA-256 does not match its header, whose header says a different format, or
  whose decompressed size exceeds `MAX_CHUNK_BYTES`;
* a `device` or `stream` id containing anything but `[A-Za-z0-9_-]`.

There is no authentication. Run it on a private network (a tailnet, a LAN) and never expose it to
the internet: anyone who can reach it can read the stream and add to it.
"""
