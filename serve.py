_SRC_RE = re.compile(
    r'Source\(id:\s*"(?P<id>[^"]+)",\s*name:\s*"(?P<name>[^"]+)",\s*origin:\s*\.(?P<origin>\w+),\s*character:\s*\.(?P<character>\w+),.*?location:\s*"(?P<location>[^"]*)",\s*effect:\s*"(?P<effect>(?:[^"\\]|\\.)*)",\s*tell:\s*"(?P<tell>(?:[^"\\]|\\.)*)",\s*mitigation:\s*"(?P<mitigation>(?:[^"\\]|\\.)*)",\s*suggestedFilter:\s*(?P<filter>SuggestedFilter\([^)]*\)|nil),\s*orderOfMagnitude:\s*"(?P<order>[^"]*)"',
    re.S)
_FILTER_RE = re.compile(r'kind:\s*\.(?P<kind>\w+),\s*hz:\s*(?P<hz>[0-9.eE+-]+|nil),\s*harmonics:\s*(?P<harm>\[[^\]]*\]|nil)')


def interference_from_swift(path: Path = INTERFERENCE_SWIFT) -> list[dict]:
    """The phone-interference catalogue IS the Swift file — no second copy to drift."""
    if not path.exists():
        return []
    text = path.read_text()
    out = []
    for m in _SRC_RE.finditer(text):
        keys = ("id", "name", "origin", "character", "location", "effect", "tell", "mitigation", "order")
        entry = {k: m.group(k) for k in keys}
        entry["orderOfMagnitude"] = entry.pop("order")
        for k in ("effect", "tell", "mitigation"):
            entry[k] = entry[k].replace('\\"', '"')
        fm = m.group("filter")
        if fm == "nil":
            entry["suggestedFilter"] = None
        else:
            f = _FILTER_RE.search(fm)
            if f:
                hz = None if f.group("hz") == "nil" else float(f.group("hz"))
                harm = None
                if f.group("harm") != "nil":
                    harm = [float(x) for x in re.findall(r'[0-9.eE+-]+', f.group("harm"))]
                entry["suggestedFilter"] = {"kind": f.group("kind"), "hz": hz, "harmonics": harm}
            else:
                entry["suggestedFilter"] = None
        out.append(entry)
    return out


def bands_from_swift(path: Path = BAND_REGISTRY_SWIFT) -> list[dict]:
    """The band registry IS the Swift file, read by `fieldlab.bands`. No second copy to drift."""
    if _band_module is None or not path.exists():
        return []
    return [{"id": b.id, "label": b.label, "lowHz": b.low_hz, "highHz": b.high_hz,
             "family": b.family, "defaultPolicy": b.default_policy, "rank": b.rank}
            for b in _band_module.BANDS]


