def _load_local_env(path: Path) -> None:
    """KEY=VALUE lines from `fieldlab.env` (git-ignored) beside this file, for settings a launcher cannot
    pass as environment variables. The real environment wins; relative paths are resolved from here."""
    if not path.is_file():
        return
    for line in path.read_text().splitlines():
        key, sep, value = line.strip().partition("=")
        if not sep or key.startswith("#") or not key.startswith("FIELDLAB_") or key in os.environ:
            continue
        value = value.strip().strip('"')
        if key in ("FIELDLAB_ANALYSIS", "FIELDLAB_STREAMS", "FIELDLAB_DESIGN") and value:
            value = str((path.parent / value).resolve())
        os.environ[key] = value


