def _runbook_module():
    """`runbook.py` is stdlib on purpose, so this server imports it rather than shelling out.

    `watch.py` usually is not (it needs numpy and scipy), which is why the two halves of the claim page
    arrive by different routes. That is the seam, not an inconsistency: ticking a checkbox must not
    cost an interpreter start.
    """
    _analysis_on_path()
    from fieldlab import runbook
    return runbook


def _analysis_on_path() -> None:
    """Make the consumer's `fieldlab` package importable, once. Appended, so it can never shadow a
    module of this repo's (a consumer's own `bands.py` once could)."""
    if str(ANALYSIS) not in sys.path:
        sys.path.append(str(ANALYSIS))


class Handler(SimpleHTTPRequestHandler):
    server_version = "FieldLab/1"
    protocol_version = "HTTP/1.1"

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(WEB), **kwargs)

    def log_message(self, fmt, *args):  # quieter
        if "/api/events" in str(args[0] if args else ""):
            return
        sys.stderr.write(f"{self.address_string()} - {fmt % args}\n")

    # -- routing helpers
    def _key(self) -> str:
        """The path with the gateway prefix removed, so routes work direct and proxied."""
        path = urlsplit(self.path).path
        for prefix in GATEWAY_PREFIXES:
            if path.startswith(prefix + "/") or path == prefix:
                path = path[len(prefix):] or "/"
        return path

    def _query(self) -> dict:
        return {k: v[-1] for k, v in parse_qs(urlsplit(self.path).query).items()}

    @staticmethod
    def _finite(value):
        """NaN and Infinity are not valid JSON and a browser rejects the whole document for one of
        them. Absence is the honest encoding of "not measured" — and this is the last line of
        defence, applied to every response rather than trusted to each producer."""
        if isinstance(value, float):
            return None if (value != value or value in (float("inf"), float("-inf"))) else value
        if isinstance(value, dict):
            return {k: Handler._finite(v) for k, v in value.items()}
        if isinstance(value, (list, tuple)):
            return [Handler._finite(v) for v in value]
        return value

    def _json(self, payload, status=200) -> None:
        body = json.dumps(self._finite(payload), allow_nan=False, default=str).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _error(self, status: int, message: str) -> None:
        self._json({"ok": False, "error": message}, status)

    def _body(self, limit: int = MAX_JSON_BYTES) -> bytes:
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0:
            return b""
        if length > limit:
            raise ValueError("body too large")
        return self.rfile.read(length)

    # -- static surface
    def end_headers(self):
        p = self._key()
        if p.startswith("/design/") or p.endswith((".css", ".js", ".html")) or p == "/":
            self.send_header("Cache-Control", "no-store")
        # CORS on READS ONLY. Other projects' pages run on their own ports, so a page on 8204
        # fetching the live stream from 8212 is cross-origin and blocked without this -- which is
        # the whole point of the tool being shared.
        #
        # Writes are closed to other origins by `do_POST`, not here: withholding allow-origin only
        # stops a page READING a response, and a cross-origin POST is still sent. Requiring a
        # JSON or chunk Content-Type forces a preflight, and OPTIONS never allows one.
        if self.command in ("GET", "HEAD", "OPTIONS"):
            self.send_header("Access-Control-Allow-Origin", "*")
        super().end_headers()

    def do_OPTIONS(self):
        self.send_response(204)
        self.send_header("Access-Control-Allow-Methods", "GET, HEAD, OPTIONS")
        self.send_header("Content-Length", "0")
        self.end_headers()

    def translate_path(self, path):
        clean = path.split("?", 1)[0].split("#", 1)[0]
        # The consumer client is served from the TOOL root, not web/, so every project takes one
        # copy from here and they cannot drift -- the same arrangement `eeg-bridge` uses for
        # `eeg-client.js`. See INTEGRATION.md.
        if self._key() == "/fieldlab-client.js":
            return str(HERE / "fieldlab-client.js")
        for prefix in GATEWAY_PREFIXES + ("",):
            key = clean[len(prefix):] if prefix and clean.startswith(prefix) else clean
            if key in DESIGN_PUBLIC:
                return str(DESIGN_PUBLIC[key])
            if key.startswith("/design/fonts/"):
                name = key[len("/design/fonts/"):]
                if "/" not in name and ".." not in name and name.endswith(".woff2"):
                    f = (DESIGN / "fonts" / name).resolve()
                    if f.is_file() and f.parent == (DESIGN / "fonts").resolve():
                        return str(f)
        key = self._key() if clean == urlsplit(self.path).path else clean
        # The consuming entry's own claim page, mounted from outside this folder. Only the file
        # types a page is made of, no traversal, and no directory listing -- CLAIM_WEB sits inside
        # a study folder that also holds analysis code and cached data.
        if key == "/watch" or key.startswith("/watch/"):
            name = key[len("/watch"):].lstrip("/") or "index.html"
            if "/" not in name and ".." not in name and name.endswith((".html", ".css", ".js")):
                candidate = (CLAIM_WEB / name).resolve()
                if candidate.is_file() and candidate.parent == CLAIM_WEB.resolve():
                    return str(candidate)
            return "/dev/null/blocked"
        # The data folder and the server's own source are not on the URL surface.
        if "/streams/" in key or key.endswith("/streams") or key.endswith(".py") or "/analysis/" in key:
            return "/dev/null/blocked"
        if key == "/":
            key = "/index.html"
        # Everything else is a file inside web/. Resolving first is what stops `/../` reaching the
        # rest of the disk; the name checks above are case-sensitive and cannot do that alone.
        candidate = (WEB / key.lstrip("/")).resolve()
        if WEB.resolve() not in candidate.parents:
            return "/dev/null/blocked"
        return str(candidate)

    # -- verbs
    def do_GET(self):
        key = self._key()
        q = self._query()
        if key == "/watch":
            # Redirect to the trailing slash so the page's own relative paths resolve: `watch.js`
            # must become /watch/watch.js, and `../design/design.css` must become /design/...
            # Without this the page loads and every asset 404s, which looks like a broken server.
            self.send_response(301)
            self.send_header("Location", urlsplit(self.path).path + "/"
                             + (("?" + urlsplit(self.path).query) if urlsplit(self.path).query else ""))
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        if key == "/api/status":
            return self._json(STORE.status())
        if key == "/api/bands":
            return self._json({"source": str(BAND_REGISTRY_SWIFT.relative_to(HERE)), "bands": bands_from_swift()})
        if key == "/api/interference":
            phil = re.search(r'philosophy = "([^"]*)"', INTERFERENCE_SWIFT.read_text())
            return self._json({"source": str(INTERFERENCE_SWIFT.relative_to(HERE)),
                               "philosophy": phil.group(1) if phil else "",
                               "sources": interference_from_swift()})
        if key == "/api/streams":
            device = q.get("device", "")
            if not _valid_id(device):
                return self._error(400, "device")
            return self._json({"device": device, "streams": [STORE.stream_summary(device, s) for s in STORE.streams(device)]})
        if key == "/api/samples":
            device = q.get("device", "")
            if not _valid_id(device):
                return self._error(400, "device")
            try:
                now = time.time()
                t1 = float(q.get("to") or now)
                t0 = float(q.get("from") or (t1 - 60))
                step = max(1, int(q.get("step") or 1))
            except ValueError:
                return self._error(400, "from/to/step must be epoch seconds / int")
            if not (math.isfinite(t0) and math.isfinite(t1) and t0 <= t1):
                return self._error(400, "from/to must be finite, with from <= to")
            if t1 - t0 > 6 * 3600 and step < 10:
                return self._error(400, "a window over 6 h needs step >= 10 — ask for bins, not every sample")
            stream = q.get("stream")
            if stream and not _valid_id(stream):
                return self._error(400, "stream")
            return self._json(STORE.samples(device, t0, t1, step, stream))
        if key == "/api/findings":
            # Everything this entry has MEASURED, assembled offline by `run.py summary` from
            # cached artefacts. Served as a plain file because this server is stdlib-only and the
            # assembly needs numpy -- the same split as every other analysis route here.
            path = HERE / "data" / "findings.json"
            if not path.is_file():
                return self._json({
                    "available": False,
                    "reason": "data/findings.json has not been generated",
                    "how": "analysis/run.py summary"})
            try:
                return self._json(json.loads(path.read_text()))
            except Exception as exc:
                return self._error(500, f"findings.json unreadable: {exc}")
        if key == "/api/station":
            device = q.get("device", "")
            if not _valid_id(device):
                return self._error(400, "device")
            return self._json(LATEST_STATION.get(device) or {"device": device, "station": None})
        if key == "/api/register":
            device = q.get("device", "")
            if not _valid_id(device):
                return self._error(400, "device")
            _analysis_on_path()
            try:
                from fieldlab import autotests, register as reg
            except Exception as exc:  # noqa: BLE001 — the sidecar is an optional sibling
                return self._error(503, f"analysis sidecar unavailable: {exc}")
            data = reg.summary(STREAMS, device)
            for sig in data["signals"]:
                sig["outstanding"] = reg.outstanding(sig, list(autotests.MANUAL_TESTS))
            return self._json(data)
        if key == "/api/claim":
            # What the CONSUMING project adds to this generic viewer, declared by it rather than
            # decided here. The recorder draws what the phone recorded; a claim page draws what
            # somebody thinks it means, and those are different jobs that were sharing one
            # dashboard. A consumer with no claim.json gets `declared: false` and a clean device
            # viewer -- which is what the second consumer of this tool should see on day one.
            path = CLAIM_WEB / "claim.json"
            if not path.is_file():
                return self._json({"declared": False,
                                   "reason": "the consuming analysis ships no watch/claim.json",
                                   "analysis": ANALYSIS.name})
            try:
                data = json.loads(path.read_text())
            except ValueError as exc:
                return self._error(500, f"claim.json unreadable: {exc}")
            data["declared"] = True
            return self._json(data)
        if key == "/api/watch":
            device = q.get("device", "")
            if not _valid_id(device):
                return self._error(400, "device")
            try:
                seconds = int(float(q.get("seconds") or 300))
            except ValueError:
                return self._error(400, "seconds must be a number")
            seconds = max(30, min(seconds, 3600))
            return self._json(WATCH.get(device, seconds))
        if key == "/api/runbook":
            device = q.get("device", "")
            if not _valid_id(device):
                return self._error(400, "device")
            try:
                runbook = _runbook_module()
            except Exception as exc:  # noqa: BLE001 — the sidecar is an optional sibling
                return self._error(503, f"analysis sidecar unavailable: {exc}")
            # The readiness gate comes from the SAME cached reading the page is showing, so a step
            # can never be greyed out against a different window than the one on screen.
            try:
                seconds = max(30, min(int(float(q.get("seconds") or 300)), 3600))
            except ValueError:
                return self._error(400, "seconds must be a number")
            reading = WATCH.get(device, seconds)
            signal = None
            try:
                from fieldlab import register as reg
                claim_hz = reading.get("claim_hz")      # the study's watch reading names its line
                for sig in reg.summary(STREAMS, device).get("signals", []) if claim_hz is not None else []:
                    if abs(float(sig.get("frequency_hz", 0)) - float(claim_hz)) < 0.25:
                        signal = sig
                        break
            except Exception:  # noqa: BLE001 — a missing register means no recorded outcome yet
                signal = None
            which = q.get("which", "tests")
            if which not in ("tests", "acquisition"):
                return self._error(400, "which must be 'tests' or 'acquisition'")
            plan = runbook.plan(STREAMS, device, reading.get("readiness"), signal, which)
            plan["which"] = which
            plan["window"] = reading.get("window")
            plan["available"] = bool(reading.get("available"))
            plan["signal_id"] = (signal or {}).get("id")
            return self._json(plan)
        if key == "/api/alerts":
            device = q.get("device", "")
            if not _valid_id(device):
                return self._error(400, "device")
            return self._json(LATEST_ALERTS.get(device) or {"device": device, "alerts": None})
        if key == "/api/jobs":
            return self._json({"jobs": JOBS.list(), "commands": ANALYZE_COMMANDS, "venv": ANALYSIS_PY.exists()})
        if key == "/api/events":
            return self._events()
        if key.startswith("/api/"):
            return self._error(404, "no such route")
        # The gateway redirects bare /slug to /slug/; direct callers get the page either way.
        return super().do_GET()

    def do_POST(self):
        key = self._key()
        ctype = (self.headers.get("Content-Type") or "").split(";", 1)[0].strip().lower()
        if ctype not in POST_CONTENT_TYPES:
            return self._error(415, f"POST needs Content-Type {' or '.join(POST_CONTENT_TYPES)}")
        try:
            if key == "/api/stream/chunk":
                body = self._body(MAX_CHUNK_BYTES)
                if not body:
                    return self._error(400, "empty body")
                compression = self.headers.get("X-FieldLab-Compression", "deflate-raw")
                try:
                    return self._json(STORE.ingest(body, compression))
                except ChunkConflict as exc:
                    return self._error(409, str(exc))
                except ValueError as exc:
                    return self._error(422, str(exc))
            if key == "/api/stream/hello":
                try:
                    payload = json.loads(self._body() or b"{}")
                    return self._json(STORE.hello(payload))
                except (ValueError, json.JSONDecodeError) as exc:
                    return self._error(422, str(exc))
            if key == "/api/register/confirm":
                # A manual test only becomes a control once a person says they ran it. This is the
                # route that records that, and it appends rather than overwrites — a source that
                # vanished on Tuesday and not on Friday is the most interesting result there is.
                try:
                    payload = json.loads(self._body() or b"{}")
                    device = payload.get("device", "")
                    if not _valid_id(device):
                        return self._error(400, "device")
                    _analysis_on_path()
                    from fieldlab import register as reg
                    updated = reg.confirm_manual_test(
                        STREAMS, device, str(payload["signal"]), str(payload["test"]),
                        str(payload["outcome"]), str(payload.get("note", ""))[:500])
                    STORE.publish("register", {"device": device, "signal": updated["id"]})
                    return self._json({"ok": True, "signal": updated})
                except KeyError as exc:
                    return self._error(400, f"missing or unknown: {exc}")
                except (ValueError, json.JSONDecodeError) as exc:
                    return self._error(400, str(exc))
            if key in ("/api/runbook/step", "/api/runbook/reset"):
                try:
                    payload = json.loads(self._body() or b"{}")
                    device = payload.get("device", "")
                    if not _valid_id(device):
                        return self._error(400, "device")
                    runbook = _runbook_module()
                    if key.endswith("/reset"):
                        data = runbook.reset(STREAMS, device, str(payload["test"]),
                                             str(payload.get("why", ""))[:200])
                    else:
                        # The gate state is taken from the SERVER's cached reading, never from the
                        # browser. A page that has been open since this morning would otherwise
                        # stamp a step with a gate state from hours ago, and that stamp is the
                        # whole point of recording it.
                        state = (WATCH.get(device, 300).get("readiness") or {}).get("state")
                        data = runbook.check(STREAMS, device, str(payload["test"]),
                                             str(payload["step"]),
                                             bool(payload.get("done", True)),
                                             str(payload.get("note", ""))[:500], state)
                    STORE.publish("runbook", {"device": device, "test": payload.get("test")})
                    return self._json({"ok": True,
                                       "progress": runbook.progress(data, str(payload["test"]))})
                except KeyError as exc:
                    return self._error(400, f"missing or unknown: {exc}")
                except (ValueError, json.JSONDecodeError) as exc:
                    return self._error(400, str(exc))
                except Exception as exc:  # noqa: BLE001
                    return self._error(503, f"analysis sidecar unavailable: {exc}")
            if key == "/api/analyze":
                try:
                    payload = json.loads(self._body() or b"{}")
                    extra = [str(x) for x in payload.get("extra", [])][:8]
                    allowed = ("--radius", "--centre", "--events", "--shape-surrogates",
                               "--surrogates", "--alpha", "--against", "--archive",
                               "--station-month", "--member")
                    if any(x.startswith("-") and x not in allowed for x in extra):
                        return self._error(400, f"extra flags limited to {'/'.join(allowed)}")
                    return self._json(JOBS.start(payload.get("command", ""), payload.get("device", ""),
                                                 float(payload["from"]), float(payload["to"]), extra))
                except (KeyError, ValueError, json.JSONDecodeError, TypeError) as exc:
                    return self._error(400, str(exc))
            return self._error(404, "no such route")
        except ValueError as exc:
            return self._error(413, str(exc))

    def _events(self):
        q = STORE.subscribe()
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-store")
        self.send_header("Connection", "keep-alive")
        self.send_header("X-Accel-Buffering", "no")
        self.end_headers()
        try:
            self.wfile.write(b"event: hello\ndata: " + json.dumps({"now": time.time()}).encode() + b"\n\n")
            self.wfile.flush()
            while True:
                try:
                    event, data = q.get(timeout=5.0)
                    self.wfile.write(f"event: {event}\ndata: {json.dumps(data)}\n\n".encode())
                except queue.Empty:
                    self.wfile.write(b"event: hb\ndata: " + json.dumps({"now": time.time()}).encode() + b"\n\n")
                self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError, OSError):
            pass
        finally:
            STORE.unsubscribe(q)


def main() -> None:
    port = int(sys.argv[1]) if len(sys.argv) > 1 else int(os.environ.get("PORT", DEFAULT_PORT))
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    server.daemon_threads = True
    print(f"FieldLab stream server on http://127.0.0.1:{port}/  (store: {STREAMS})", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
