class WatchCache:
    """`run.py watch` behind a short TTL.

    The claim page polls this, and a subprocess per poll per open tab is a lot of interpreter
    starts for a number that only changes when a chunk lands. The TTL is deliberately shorter than
    the shortest chunk setting (5 s), so a fresh chunk is never hidden behind a stale reading.

    Every entry carries the age of the window it describes. **A scan describes a window, never
    "now"** -- the same rule `/api/alerts` follows, and the single most misreadable thing on a page
    that updates itself.
    """

    TTL_S = 4.0

    def __init__(self):
        self._lock = threading.Lock()
        self._hot: dict[tuple[str, int], tuple[float, dict]] = {}

    def get(self, device: str, seconds: int) -> dict:
        key = (device, seconds)
        now = time.time()
        with self._lock:
            hit = self._hot.get(key)
            if hit and now - hit[0] < self.TTL_S:
                return dict(hit[1], cached=True)
        payload = self._run(device, seconds)
        with self._lock:
            self._hot[key] = (now, payload)
        return dict(payload, cached=False)

    def _run(self, device: str, seconds: int) -> dict:
        if not ANALYSIS_PY.exists():
            return {"ok": False, "available": False,
                    "reason": f"the analysis venv is missing at {ANALYSIS_PY}",
                    "readiness": {"ready": False, "state": "no-reading",
                                  "say": "The analysis sidecar is not installed.",
                                  "do": "See the entry's RUN.md — the venv is one command."}}
        argv = [str(ANALYSIS_PY), str(ANALYSIS / "run.py"), "watch",
                "--stream", str(STREAMS / device), "--seconds", str(seconds)]
        try:
            proc = subprocess.run(argv, capture_output=True, text=True, timeout=90,
                                  cwd=str(ANALYSIS))
        except subprocess.TimeoutExpired:
            return {"ok": False, "available": False,
                    "reason": "the reading took over 90 s — ask for a shorter --seconds",
                    "readiness": {"ready": False, "state": "no-reading",
                                  "say": "The reading timed out.", "do": "Try a shorter window."}}
        if proc.returncode != 0 or not proc.stdout.strip():
            # The LAST line of a traceback is the exception; the rest is this machine's paths.
            # Putting a whole traceback in an HTTP body is a path leak and unreadable besides.
            tail = (proc.stderr or "no output").strip().splitlines()
            return {"ok": False, "available": False,
                    "reason": (tail[-1] if tail else "no output")[:300],
                    "readiness": {"ready": False, "state": "no-reading",
                                  "say": "The reading failed.", "do": "Check the server log."}}
        try:
            return json.loads(proc.stdout)
        except json.JSONDecodeError as exc:
            return {"ok": False, "available": False, "reason": f"unreadable reading: {exc}"}


